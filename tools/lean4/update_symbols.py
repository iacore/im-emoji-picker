#!/usr/bin/env python3
"""Write src/res/lean4-symbols.tsv from the Lean 4 VS Code extension.

The abbreviation table is what `\\pi` turns into inside a Lean file: the
extension keeps it as a JSON object in module 3116 of its bundled
`dist/extension.js`, keyed by abbreviation (without the leading backslash) and
valued by the text it inserts.  The picker reads the same table so a query
typed there finds the symbols a Lean author already knows.

Placeholders the extension resolves at insertion time (`$CURSOR`) are dropped:
the picker has no cursor inside the picker window to place.

  python3 tools/lean4/update_symbols.py                 # newest installed copy
  python3 tools/lean4/update_symbols.py path/to/extension.js
"""

from __future__ import annotations

import argparse
import glob
import json
import os
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "src" / "res" / "lean4-symbols.tsv"

MODULE = """3116:e=>{"use strict";e.exports=JSON.parse('"""
CURSOR = "$CURSOR"


def find_extension() -> Path:
    patterns = [
        "~/.vscode-oss/extensions/leanprover.lean4-*/dist/extension.js",
        "~/.vscode/extensions/leanprover.lean4-*/dist/extension.js",
        "~/.vscode-server/extensions/leanprover.lean4-*/dist/extension.js",
    ]
    found: list[str] = []
    for pattern in patterns:
        found.extend(glob.glob(os.path.expanduser(pattern)))
    if not found:
        sys.exit("no leanprover.lean4 extension found; pass extension.js as an argument")
    return Path(sorted(found)[-1])


def read_table(path: Path) -> dict[str, str]:
    source = path.read_text(encoding="utf-8")
    start = source.find(MODULE)
    if start < 0:
        sys.exit(f"{path}: module 3116 (the abbreviation table) not found")
    start += len(MODULE) - 1  # keep the opening quote of the JSON string literal
    end = source.find("')}", start)
    if end < 0:
        sys.exit(f"{path}: the abbreviation table is not terminated")
    # The table is a JavaScript string literal holding JSON, so it is unescaped
    # once as JavaScript and then parsed as JSON.  The literal is a single
    # quoted string, hence the wrapping.
    return json.loads(eval_js_string(source[start:end + 1]))


def eval_js_string(literal: str) -> str:
    """Decode one single-quoted JavaScript string literal without running it."""
    out: list[str] = []
    i = 1  # skip the opening quote
    while i < len(literal):
        c = literal[i]
        if c == "'":
            break
        if c != "\\":
            out.append(c)
            i += 1
            continue
        n = literal[i + 1]
        if n == "u":
            out.append(chr(int(literal[i + 2:i + 6], 16)))
            i += 6
        elif n == "x":
            out.append(chr(int(literal[i + 2:i + 4], 16)))
            i += 4
        elif n == "n":
            out.append("\n")
            i += 2
        elif n == "t":
            out.append("\t")
            i += 2
        else:
            out.append(n)
            i += 2
    return "".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("extension_js", nargs="?", help="path to the extension's dist/extension.js")
    args = parser.parse_args()

    source = Path(args.extension_js).expanduser() if args.extension_js else find_extension()
    try:
        origin = Path(*source.parts[-3:]).as_posix()
    except Exception:  # a very short path; keep whatever was given
        origin = source.name
    table = read_table(source)

    rows: list[tuple[str, str]] = []
    for abbreviation, symbol in table.items():
        text = symbol.replace(CURSOR, "")
        if not text:
            continue
        if any(ord(ch) < 0x20 or ch == "\t" or ch == "\n" for ch in text):
            sys.exit(f"{source}: {abbreviation!r} inserts control characters")
        rows.append((abbreviation, text))
    rows.sort()

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8") as handle:
        handle.write("# Lean 4 unicode input abbreviations, from the Lean 4 VS Code extension.\n")
        handle.write("# Generated by tools/lean4/update_symbols.py from\n")
        handle.write(f"# {origin}\n")
        handle.write("# abbreviation<TAB>inserted text\n")
        for abbreviation, text in rows:
            handle.write(f"{abbreviation}\t{text}\n")
    print(f"{len(rows)} abbreviations -> {OUT}")


if __name__ == "__main__":
    main()
